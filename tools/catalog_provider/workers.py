'''Pluggable workers for the catalog provider daemon.'''
import re
from dataclasses import dataclass
from pathlib import Path

TARGET_KEYS = ('repo', 'path', 'target', 'dir', 'directory', 'project')
QUOTE = chr(34)

@dataclass
class Deliverable:
    content: str
    filename: str
    media_type: str = 'text/markdown'

def parse_note(note):
    meta = {}
    for line in (note or '').splitlines():
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, _, value = line.partition('=')
        meta[key.strip().lower()] = value.strip()
    return meta

def note_of(order):
    for key in ('note', 'notes', 'details', 'description', 'instructions'):
        value = order.get(key)
        if isinstance(value, str) and value.strip():
            return value
    return ''

def resolve_target(order, base_dir):
    meta = parse_note(note_of(order))
    raw = ''
    for key in TARGET_KEYS:
        if meta.get(key):
            raw = meta[key]
            break
    base = Path(base_dir)
    target = Path(raw).expanduser() if raw else base
    if not target.is_absolute():
        target = (base / target).resolve()
    return target

def iter_files(target, patterns, limit):
    if target.is_file():
        return [target]
    if not target.is_dir():
        return []
    found = []
    for pattern in patterns:
        for path in sorted(target.rglob(pattern)):
            if not path.is_file():
                continue
            if any(part.startswith('.') for part in path.relative_to(target).parts):
                continue
            found.append(path)
            if len(found) >= limit:
                return found
    return found

def rel(path, target):
    try:
        return str(path.relative_to(target))
    except ValueError:
        return path.name

def cell(value):
    return str(value).replace('|', r'\|')

class Worker:
    name = 'base'
    def work(self, order):
        raise NotImplementedError

class DocsLintWorker(Worker):
    name = 'docs-lint'
    max_files = 200
    max_line_length = 200
    max_findings = 500
    def __init__(self, base_dir=None):
        self.base_dir = Path(base_dir) if base_dir else Path.cwd()
    def work(self, order):
        target = resolve_target(order, self.base_dir)
        header = '# Docs lint report\n\nTarget: `%s`\n\n' % target
        if not target.exists():
            return Deliverable(header + 'Target path missing on provider host.\n', 'docs-lint.md')
        files = iter_files(target, ('*.md', '*.markdown', '*.rst'), self.max_files)
        if not files:
            return Deliverable(header + 'No documentation files found.\n', 'docs-lint.md')
        findings = []
        for path in files:
            name = rel(path, target)
            try:
                text = path.read_text(encoding='utf-8', errors='replace')
            except OSError as exc:
                findings.append((name, 0, 'unreadable: %s' % exc))
                continue
            lines = text.splitlines()
            for number, line in enumerate(lines, 1):
                if line.rstrip() != line:
                    findings.append((name, number, 'trailing whitespace'))
                if '\t' in line:
                    findings.append((name, number, 'tab character'))
                if len(line) > self.max_line_length:
                    findings.append((name, number, 'line too long'))
                if line.strip().startswith('#') and not line.replace('#', '').strip():
                    findings.append((name, number, 'empty heading'))
            if text and not text.endswith('\n'):
                findings.append((name, len(lines), 'missing trailing newline'))
            if text.count('```') % 2:
                findings.append((name, len(lines), 'unbalanced code fence'))
        return Deliverable(self.render(header, len(files), findings), 'docs-lint.md')
    def render(self, header, file_count, findings):
        out = [header, 'Files scanned: %d\n\n' % file_count]
        if not findings:
            out.append('No issues found.\n')
        else:
            out.append('Issues found: %d\n\n' % len(findings))
            out.append('| File | Line | Finding |\n| --- | --- | --- |\n')
            for name, number, message in findings[:self.max_findings]:
                out.append('| `%s` | %s | %s |\n' % (cell(name), number or '-', cell(message)))
            if len(findings) > self.max_findings:
                out.append('\n_Report truncated._\n')
        out.append('\n---\nGenerated by the RustChain catalog provider `docs-lint` worker.\n')
        return ''.join(out)

CHECKS = (
    ('high', re.compile(r'(?i)\b(password|passwd|api_key|secret|private_key)\b\s*=\s*[' + QUOTE + r'][^' + QUOTE + r']{6,}[' + QUOTE + r']'), 'possible hard-coded credential'),
    ('medium', re.compile(r'^\s*except\s*:\s*$'), 'bare except clause'),
    ('medium', re.compile(r'^\s*except\s+Exception\s*:'), 'catches broad Exception'),
    ('low', re.compile(r'\bprint\('), 'debug print call'),
    ('low', re.compile(r'\bTODO\b'), 'TODO marker'),
    ('low', re.compile(r'\bFIXME\b'), 'FIXME marker'),
)

class CodeReviewWorker(Worker):
    name = 'code-review'
    max_files = 100
    max_lines = 400
    max_findings = 300
    def __init__(self, base_dir=None):
        self.base_dir = Path(base_dir) if base_dir else Path.cwd()
    def work(self, order):
        target = resolve_target(order, self.base_dir)
        header = '# Code review\n\nTarget: `%s`\n\n' % target
        if not target.exists():
            return Deliverable(header + 'Target path missing on provider host.\n', 'code-review.md')
        files = iter_files(target, ('*.py', '*.js', '*.ts', '*.rs', '*.go'), self.max_files)
        if not files:
            return Deliverable(header + 'No source files found.\n', 'code-review.md')
        findings = []
        stats = []
        for path in files:
            name = rel(path, target)
            try:
                text = path.read_text(encoding='utf-8', errors='replace')
            except OSError as exc:
                findings.append((name, 0, 'unreadable: %s' % exc))
                continue
            lines = text.splitlines()
            stats.append((name, len(lines)))
            for number, line in enumerate(lines[:self.max_lines], 1):
                for severity, pattern, message in CHECKS:
                    if pattern.search(line):
                        findings.append((name, number, '%s: %s' % (severity, message)))
        return Deliverable(self.render(header, stats, findings), 'code-review.md')
    def render(self, header, stats, findings):
        out = [header, 'Files reviewed: %d\n\n' % len(stats)]
        if stats:
            out.append('| File | Lines |\n| --- | --- |\n')
            for name, count in stats:
                out.append('| `%s` | %d |\n' % (cell(name), count))
            out.append('\n')
        if not findings:
            out.append('No findings.\n')
        else:
            out.append('Findings: %d\n\n' % len(findings))
            out.append('| File | Line | Finding |\n| --- | --- | --- |\n')
            for name, number, message in findings[:self.max_findings]:
                out.append('| `%s` | %s | %s |\n' % (cell(name), number or '-', cell(message)))
        out.append('\n---\nGenerated by the RustChain catalog provider `code-review` worker.\n')
        return ''.join(out)
